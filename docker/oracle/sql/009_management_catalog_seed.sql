-- 프로그램 기능 grant는 현재 카탈로그의 메뉴/프로그램/기능 조합만 선택한다.
MERGE INTO PM_AUTH_ACTION target
USING (
    SELECT 'AUTH_SYSTEM_ADMIN' AUTHORITY_ID,
           action.MENU_ID, action.PROGRAM_ID, action.ACTION_ID
      FROM PM_PROGRAM_ACTION action
     WHERE (action.MENU_ID = 'CONTENT_LIST' AND action.PROGRAM_ID = 'CONTENT'
                AND action.ACTION_ID IN ('CONTENT_READ', 'CONTENT_EXPORT', 'CONTENT_SAVE',
                                         'CONTENT_PUBLISH', 'CONTENT_DELETE_OLD'))
        OR (action.MENU_ID = 'CONTENT_EDITOR' AND action.PROGRAM_ID = 'CONTENT'
                AND action.ACTION_ID IN ('CONTENT_CREATE', 'CONTENT_REVIEW'))
        OR (action.MENU_ID = 'CONTENT_PUBLISH' AND action.PROGRAM_ID = 'CONTENT'
                AND action.ACTION_ID = 'CONTENT_ARCHIVE')
        OR (action.MENU_ID = 'SYSTEM_AUTH' AND action.PROGRAM_ID = 'AUTHORITY'
                AND action.ACTION_ID IN ('AUTHORITY_READ', 'AUTHORITY_UPDATE'))
        OR (action.MENU_ID = 'SYSTEM_AUTH_REQUEST' AND action.PROGRAM_ID = 'AUTHORITY'
                AND action.ACTION_ID IN ('AUTHORITY_REQUEST_READ', 'AUTHORITY_APPROVE', 'AUTHORITY_REJECT'))
        OR (action.MENU_ID = 'SYSTEM_MENU' AND action.PROGRAM_ID = 'MENU'
                AND action.ACTION_ID IN ('MENU_READ', 'MENU_SAVE', 'MENU_GRANT', 'MENU_DEACTIVATE'))
        OR (action.MENU_ID = 'SYSTEM_PROGRAM' AND action.PROGRAM_ID = 'PROGRAM'
                AND action.ACTION_ID IN ('PROGRAM_READ', 'PROGRAM_SAVE', 'PROGRAM_ACTION_SAVE', 'PROGRAM_GRANT'))
        OR (action.MENU_ID = 'SYSTEM_PROJECT' AND action.PROGRAM_ID = 'PROJECT'
                AND action.ACTION_ID IN ('PROJECT_READ', 'PROJECT_CREATE', 'PROJECT_UPDATE',
                                         'PROJECT_MEMBER_MANAGE', 'PROJECT_OWNER_TRANSFER', 'PROJECT_ARCHIVE'))
        OR (action.MENU_ID = 'PROJECT_WORKSPACE' AND action.PROGRAM_ID = 'PROJECT'
                AND action.ACTION_ID = 'PROJECT_TASK_UPDATE')
        OR (action.MENU_ID = 'PROJECT_REPORT' AND action.PROGRAM_ID = 'PROJECT'
                AND action.ACTION_ID = 'PROJECT_REPORT_READ')
        OR (action.MENU_ID = 'SYSTEM_CODE' AND action.PROGRAM_ID = 'COMMON_CODE'
                AND action.ACTION_ID IN ('COMMON_CODE_READ', 'COMMON_CODE_SAVE', 'COMMON_CODE_GROUP_SAVE',
                                         'COMMON_CODE_DEACTIVATE', 'COMMON_CODE_DELETE',
                                         'COMMON_CODE_BULK_IMPORT'))
        OR (action.MENU_ID = 'SYSTEM_AUDIT' AND action.PROGRAM_ID = 'AUDIT'
                AND action.ACTION_ID IN ('AUDIT_READ', 'AUDIT_EXPORT'))
    UNION ALL
    SELECT 'AUTH_AUTHORITY_MANAGER', action.MENU_ID, action.PROGRAM_ID, action.ACTION_ID
      FROM PM_PROGRAM_ACTION action
     WHERE (action.MENU_ID = 'SYSTEM_AUTH' AND action.PROGRAM_ID = 'AUTHORITY'
                AND action.ACTION_ID IN ('AUTHORITY_READ', 'AUTHORITY_UPDATE'))
        OR (action.MENU_ID = 'SYSTEM_AUTH_REQUEST' AND action.PROGRAM_ID = 'AUTHORITY'
                AND action.ACTION_ID IN ('AUTHORITY_REQUEST_READ', 'AUTHORITY_APPROVE', 'AUTHORITY_REJECT'))
        OR (action.MENU_ID = 'SYSTEM_AUDIT' AND action.PROGRAM_ID = 'AUDIT'
                AND action.ACTION_ID = 'AUDIT_READ')
    UNION ALL
    SELECT 'AUTH_PROGRAM_MANAGER', action.MENU_ID, action.PROGRAM_ID, action.ACTION_ID
      FROM PM_PROGRAM_ACTION action
     WHERE (action.MENU_ID = 'SYSTEM_MENU' AND action.PROGRAM_ID = 'MENU'
                AND action.ACTION_ID IN ('MENU_READ', 'MENU_SAVE', 'MENU_GRANT', 'MENU_DEACTIVATE'))
        OR (action.MENU_ID = 'SYSTEM_PROGRAM' AND action.PROGRAM_ID = 'PROGRAM'
                AND action.ACTION_ID IN ('PROGRAM_READ', 'PROGRAM_SAVE', 'PROGRAM_ACTION_SAVE', 'PROGRAM_GRANT'))
        OR (action.MENU_ID = 'SYSTEM_AUDIT' AND action.PROGRAM_ID = 'AUDIT'
                AND action.ACTION_ID = 'AUDIT_READ')
    UNION ALL
    SELECT 'AUTH_PROJECT_MANAGER', action.MENU_ID, action.PROGRAM_ID, action.ACTION_ID
      FROM PM_PROGRAM_ACTION action
     WHERE (action.MENU_ID = 'SYSTEM_PROJECT' AND action.PROGRAM_ID = 'PROJECT'
                AND action.ACTION_ID IN ('PROJECT_READ', 'PROJECT_CREATE', 'PROJECT_UPDATE',
                                         'PROJECT_MEMBER_MANAGE', 'PROJECT_OWNER_TRANSFER', 'PROJECT_ARCHIVE'))
        OR (action.MENU_ID = 'PROJECT_WORKSPACE' AND action.PROGRAM_ID = 'PROJECT'
                AND action.ACTION_ID = 'PROJECT_TASK_UPDATE')
        OR (action.MENU_ID = 'PROJECT_REPORT' AND action.PROGRAM_ID = 'PROJECT'
                AND action.ACTION_ID = 'PROJECT_REPORT_READ')
    UNION ALL
    SELECT 'AUTH_CODE_MANAGER', action.MENU_ID, action.PROGRAM_ID, action.ACTION_ID
      FROM PM_PROGRAM_ACTION action
     WHERE (action.MENU_ID = 'SYSTEM_CODE' AND action.PROGRAM_ID = 'COMMON_CODE'
                AND action.ACTION_ID IN ('COMMON_CODE_READ', 'COMMON_CODE_SAVE', 'COMMON_CODE_GROUP_SAVE',
                                         'COMMON_CODE_DEACTIVATE', 'COMMON_CODE_DELETE',
                                         'COMMON_CODE_BULK_IMPORT'))
        OR (action.MENU_ID = 'SYSTEM_AUDIT' AND action.PROGRAM_ID = 'AUDIT'
                AND action.ACTION_ID = 'AUDIT_READ')
    UNION ALL
    SELECT 'AUTH_CONTENT_MANAGER', action.MENU_ID, action.PROGRAM_ID, action.ACTION_ID
      FROM PM_PROGRAM_ACTION action
     WHERE (action.MENU_ID = 'CONTENT_LIST' AND action.PROGRAM_ID = 'CONTENT'
                AND action.ACTION_ID IN ('CONTENT_READ', 'CONTENT_SAVE', 'CONTENT_PUBLISH'))
        OR (action.MENU_ID = 'CONTENT_EDITOR' AND action.PROGRAM_ID = 'CONTENT'
                AND action.ACTION_ID IN ('CONTENT_CREATE', 'CONTENT_REVIEW'))
        OR (action.MENU_ID = 'CONTENT_PUBLISH' AND action.PROGRAM_ID = 'CONTENT'
                AND action.ACTION_ID = 'CONTENT_ARCHIVE')
    UNION ALL
    SELECT 'AUTH_AUDITOR', action.MENU_ID, action.PROGRAM_ID, action.ACTION_ID
      FROM PM_PROGRAM_ACTION action
     WHERE (action.MENU_ID = 'CONTENT_LIST' AND action.PROGRAM_ID = 'CONTENT'
                AND action.ACTION_ID IN ('CONTENT_READ', 'CONTENT_EXPORT'))
        OR (action.MENU_ID = 'SYSTEM_AUTH' AND action.PROGRAM_ID = 'AUTHORITY'
                AND action.ACTION_ID = 'AUTHORITY_READ')
        OR (action.MENU_ID = 'SYSTEM_PROGRAM' AND action.PROGRAM_ID = 'PROGRAM'
                AND action.ACTION_ID = 'PROGRAM_READ')
        OR (action.MENU_ID = 'SYSTEM_PROJECT' AND action.PROGRAM_ID = 'PROJECT'
                AND action.ACTION_ID = 'PROJECT_READ')
        OR (action.MENU_ID = 'PROJECT_REPORT' AND action.PROGRAM_ID = 'PROJECT'
                AND action.ACTION_ID = 'PROJECT_REPORT_READ')
        OR (action.MENU_ID = 'SYSTEM_CODE' AND action.PROGRAM_ID = 'COMMON_CODE'
                AND action.ACTION_ID = 'COMMON_CODE_READ')
        OR (action.MENU_ID = 'SYSTEM_AUDIT' AND action.PROGRAM_ID = 'AUDIT'
                AND action.ACTION_ID IN ('AUDIT_READ', 'AUDIT_EXPORT'))
    UNION ALL
    SELECT 'AUTH_VIEWER', action.MENU_ID, action.PROGRAM_ID, action.ACTION_ID
      FROM PM_PROGRAM_ACTION action
     WHERE action.MENU_ID = 'CONTENT_LIST'
       AND action.PROGRAM_ID = 'CONTENT'
       AND action.ACTION_ID = 'CONTENT_READ'
) source
ON (target.AUTHORITY_ID = source.AUTHORITY_ID
    AND target.MENU_ID = source.MENU_ID
    AND target.PROGRAM_ID = source.PROGRAM_ID
    AND target.ACTION_ID = source.ACTION_ID)
WHEN NOT MATCHED THEN INSERT (
    AUTHORITY_ID, MENU_ID, PROGRAM_ID, ACTION_ID, CREATED_AT, CREATED_BY
) VALUES (
    source.AUTHORITY_ID, source.MENU_ID, source.PROGRAM_ID, source.ACTION_ID,
    SYSTIMESTAMP, 'SYSTEM'
);

