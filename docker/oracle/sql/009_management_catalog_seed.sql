-- AuthorizationCatalog의 확장 관리 시나리오를 Oracle 원장과 맞추는 멱등 시드다.
-- 기존 시드의 추가 행은 보존하되 동일 ID는 현재 카탈로그 정의로 갱신한다.

DECLARE
    column_count NUMBER;
BEGIN
    SELECT COUNT(*)
      INTO column_count
      FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'PM_ORGANIZATION'
       AND COLUMN_NAME = 'PARENT_ORG_ID';

    IF column_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE PM_ORGANIZATION ADD PARENT_ORG_ID VARCHAR2(30)';
    END IF;
END;
/

MERGE INTO PM_ORGANIZATION target
USING (
    SELECT 'HQ' ORG_ID, '본사' ORG_NAME, CAST(NULL AS VARCHAR2(30)) PARENT_ORG_ID,
           'Y' USE_YN, 10 SORT_ORDER FROM DUAL
    UNION ALL SELECT 'PLATFORM', '플랫폼실', 'HQ', 'Y', 20 FROM DUAL
    UNION ALL SELECT 'CONTENT', '콘텐츠실', 'HQ', 'Y', 30 FROM DUAL
    UNION ALL SELECT 'AUDIT', '감사실', 'HQ', 'Y', 40 FROM DUAL
    UNION ALL SELECT 'BRANCH_A', '이전 지점', 'HQ', 'N', 50 FROM DUAL
    UNION ALL SELECT 'BRANCH_B', '중부 지점', 'HQ', 'Y', 60 FROM DUAL
    UNION ALL SELECT 'BRANCH_SEOUL', '서울 지점', 'HQ', 'Y', 70 FROM DUAL
    UNION ALL SELECT 'BRANCH_BUSAN', '부산 지점', 'HQ', 'Y', 80 FROM DUAL
) source
ON (target.ORG_ID = source.ORG_ID)
WHEN MATCHED THEN UPDATE SET
    target.ORG_NAME = source.ORG_NAME,
    target.PARENT_ORG_ID = source.PARENT_ORG_ID,
    target.USE_YN = source.USE_YN,
    target.SORT_ORDER = source.SORT_ORDER,
    target.UPDATED_AT = SYSTIMESTAMP,
    target.UPDATED_BY = 'SYSTEM'
WHEN NOT MATCHED THEN INSERT (
    ORG_ID, ORG_NAME, PARENT_ORG_ID, USE_YN, SORT_ORDER, CREATED_BY, UPDATED_BY
) VALUES (
    source.ORG_ID, source.ORG_NAME, source.PARENT_ORG_ID, source.USE_YN,
    source.SORT_ORDER, 'SYSTEM', 'SYSTEM'
);

DECLARE
    constraint_count NUMBER;
BEGIN
    SELECT COUNT(*)
      INTO constraint_count
      FROM USER_CONSTRAINTS
     WHERE TABLE_NAME = 'PM_ORGANIZATION'
       AND CONSTRAINT_NAME = 'FK_PM_ORG_PARENT';

    IF constraint_count = 0 THEN
        EXECUTE IMMEDIATE
            'ALTER TABLE PM_ORGANIZATION ADD CONSTRAINT FK_PM_ORG_PARENT '
            || 'FOREIGN KEY (PARENT_ORG_ID) REFERENCES PM_ORGANIZATION (ORG_ID)';
    END IF;
END;
/

