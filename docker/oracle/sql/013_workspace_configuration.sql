-- 기존 데이터는 최초 컬럼 추가 때만 변환한다. 재실행해도 관리자가 변경한 영역·화면을 보존한다.
DECLARE
    column_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO column_count FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'PM_MENU' AND COLUMN_NAME = 'MENU_AREA';
    IF column_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE PM_MENU ADD (MENU_AREA VARCHAR2(10) DEFAULT ''USER'' NOT NULL CHECK (MENU_AREA IN (''USER'', ''ADMIN'')))';
        EXECUTE IMMEDIATE 'UPDATE PM_MENU SET MENU_AREA = ''ADMIN'' WHERE MENU_ID IN
            (SELECT MENU_ID FROM PM_MENU START WITH MENU_ID = ''SYSTEM'' CONNECT BY NOCYCLE PRIOR MENU_ID = PARENT_MENU_ID)';
    END IF;
    SELECT COUNT(*) INTO column_count FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'PM_PROGRAM' AND COLUMN_NAME = 'SCREEN_CODE';
    IF column_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE PM_PROGRAM ADD (SCREEN_CODE VARCHAR2(30) DEFAULT ''NONE'' NOT NULL CHECK (SCREEN_CODE IN (''NONE'', ''CONTENT_DEMO'', ''AUTHORITY_REQUEST'')))';
        EXECUTE IMMEDIATE 'UPDATE PM_PROGRAM SET SCREEN_CODE = ''CONTENT_DEMO'' WHERE PROGRAM_ID = ''CONTENT''';
    END IF;
    EXECUTE IMMEDIATE 'COMMENT ON COLUMN PM_MENU.MENU_AREA IS ''화면 영역: USER 사용자, ADMIN 관리자''';
    EXECUTE IMMEDIATE 'COMMENT ON COLUMN PM_PROGRAM.SCREEN_CODE IS ''연결할 구현 화면: NONE, CONTENT_DEMO, AUTHORITY_REQUEST''';
    COMMIT;
END;
/
