-- 네 관리 영역을 실제 업무 시나리오로 확인하기 위한 확장 기준정보.
-- 단순 행 수 채우기가 아니라 조직·사용자·권한·메뉴·프로그램·프로젝트·코드가 서로 연결되도록 구성한다.

MERGE INTO PM_ORGANIZATION target
USING (
    SELECT 'DIGITAL' ORG_ID, '디지털서비스실' ORG_NAME, 20 SORT_ORDER FROM DUAL
    UNION ALL SELECT 'SECURITY', '정보보안실', 30 FROM DUAL
    UNION ALL SELECT 'DATA', '데이터전략실', 40 FROM DUAL
    UNION ALL SELECT 'OPERATIONS', '서비스운영실', 50 FROM DUAL
) source
ON (target.ORG_ID = source.ORG_ID)
WHEN NOT MATCHED THEN INSERT (
    ORG_ID, ORG_NAME, SORT_ORDER, CREATED_BY, UPDATED_BY
) VALUES (
    source.ORG_ID, source.ORG_NAME, source.SORT_ORDER, 'SYSTEM', 'SYSTEM'
);

MERGE INTO PM_USER_PROFILE target
USING (
    SELECT 'approver' USERNAME, '권한 승인자' DISPLAY_NAME, 'SECURITY' CURRENT_ORG_ID FROM DUAL
    UNION ALL SELECT 'programManager', '프로그램 관리자', 'DIGITAL' FROM DUAL
    UNION ALL SELECT 'projectLead', '프로젝트 책임자', 'DIGITAL' FROM DUAL
    UNION ALL SELECT 'codeManager', '기준정보 관리자', 'DATA' FROM DUAL
    UNION ALL SELECT 'auditor', '감사 담당자', 'SECURITY' FROM DUAL
    UNION ALL SELECT 'developer', '서비스 개발자', 'DIGITAL' FROM DUAL
    UNION ALL SELECT 'operator', '서비스 운영자', 'OPERATIONS' FROM DUAL
    UNION ALL SELECT 'analyst', '데이터 분석가', 'DATA' FROM DUAL
) source
ON (target.USERNAME = source.USERNAME)
WHEN NOT MATCHED THEN INSERT (
    USERNAME, DISPLAY_NAME, CURRENT_ORG_ID, CREATED_BY, UPDATED_BY
) VALUES (
    source.USERNAME, source.DISPLAY_NAME, source.CURRENT_ORG_ID, 'SYSTEM', 'SYSTEM'
);

MERGE INTO PM_AUTHORITY target
USING (
    SELECT 'AUTH_AUTHORITY_APPROVER' AUTHORITY_ID, '권한 승인 관리자' AUTHORITY_NAME,
           '권한 신청을 승인하거나 반려한다.' DESCRIPTION FROM DUAL
    UNION ALL SELECT 'AUTH_PROGRAM_MANAGER', '프로그램 관리자', '메뉴·프로그램·기능과 매핑을 관리한다.' FROM DUAL
    UNION ALL SELECT 'AUTH_PROJECT_MANAGER', '프로젝트 관리자', '프로젝트와 참여자 역할을 관리한다.' FROM DUAL
    UNION ALL SELECT 'AUTH_CODE_MANAGER', '공통코드 관리자', '코드 그룹과 상세 코드를 관리한다.' FROM DUAL
    UNION ALL SELECT 'AUTH_AUDITOR', '감사 조회자', '관리 변경과 접근 감사 이력을 조회한다.' FROM DUAL
    UNION ALL SELECT 'AUTH_PROJECT_MEMBER', '프로젝트 참여자', '참여 프로젝트의 기본 업무를 조회한다.' FROM DUAL
) source
ON (target.AUTHORITY_ID = source.AUTHORITY_ID)
WHEN NOT MATCHED THEN INSERT (
    AUTHORITY_ID, AUTHORITY_NAME, ACTIVE_YN, DESCRIPTION, CREATED_BY, UPDATED_BY
) VALUES (
    source.AUTHORITY_ID, source.AUTHORITY_NAME, 'Y', source.DESCRIPTION, 'SYSTEM', 'SYSTEM'
);

MERGE INTO PM_PROGRAM target
USING (
    SELECT 'AUTH_REQUEST' PROGRAM_ID, '권한 신청·승인' PROGRAM_NAME,
           '권한 신청, 승인, 반려, 취소와 상태 이력' DESCRIPTION FROM DUAL
    UNION ALL SELECT 'MENU', '메뉴 관리', '계층 메뉴와 권한별 접근 매핑 관리' FROM DUAL
    UNION ALL SELECT 'PROGRAM', '프로그램 관리', '프로그램·기능과 권한별 실행 매핑 관리' FROM DUAL
    UNION ALL SELECT 'AUDIT', '감사 이력', '관리 변경과 접근 거부 이력 조회' FROM DUAL
) source
ON (target.PROGRAM_ID = source.PROGRAM_ID)
WHEN NOT MATCHED THEN INSERT (
    PROGRAM_ID, PROGRAM_NAME, DESCRIPTION, ACTIVE_YN, CREATED_BY, UPDATED_BY
) VALUES (
    source.PROGRAM_ID, source.PROGRAM_NAME, source.DESCRIPTION, 'Y', 'SYSTEM', 'SYSTEM'
);

MERGE INTO PM_CODE_GROUP target
USING (
    SELECT 'PROJECT_STATUS' GROUP_CODE, '프로젝트 상태' GROUP_NAME, '프로젝트 진행 상태' DESCRIPTION FROM DUAL
    UNION ALL SELECT 'PROJECT_PRIORITY', '프로젝트 우선순위', '프로젝트 추진 우선순위' FROM DUAL
    UNION ALL SELECT 'PROJECT_ROLE', '프로젝트 역할', '프로젝트 참여자 역할' FROM DUAL
    UNION ALL SELECT 'REQUEST_STATUS', '권한 신청 상태', '권한 신청과 승인 처리 상태' FROM DUAL
    UNION ALL SELECT 'ASSIGNMENT_TYPE', '권한 부여 유형', '직접 또는 위임 권한 유형' FROM DUAL
    UNION ALL SELECT 'AUDIT_RESULT', '감사 결과', '감사 이벤트 처리 결과' FROM DUAL
    UNION ALL SELECT 'ORGANIZATION_TYPE', '조직 유형', '조직 기준 분류' FROM DUAL
) source
ON (target.GROUP_CODE = source.GROUP_CODE)
WHEN NOT MATCHED THEN INSERT (
    GROUP_CODE, GROUP_NAME, ACTIVE_YN, VERSION_NO, DESCRIPTION, CREATED_BY, UPDATED_BY
) VALUES (
    source.GROUP_CODE, source.GROUP_NAME, 'Y', 1, source.DESCRIPTION, 'SYSTEM', 'SYSTEM'
);

