MERGE INTO PM_USER_AUTH_HIST target
USING (
    SELECT 'approver' USERNAME, 'SECURITY' ORG_ID, 'AUTH_AUTHORITY_APPROVER' AUTHORITY_ID FROM DUAL
    UNION ALL SELECT 'programManager', 'DIGITAL', 'AUTH_PROGRAM_MANAGER' FROM DUAL
    UNION ALL SELECT 'projectLead', 'DIGITAL', 'AUTH_PROJECT_MANAGER' FROM DUAL
    UNION ALL SELECT 'codeManager', 'DATA', 'AUTH_CODE_MANAGER' FROM DUAL
    UNION ALL SELECT 'auditor', 'SECURITY', 'AUTH_AUDITOR' FROM DUAL
    UNION ALL SELECT 'developer', 'DIGITAL', 'AUTH_PROJECT_MEMBER' FROM DUAL
    UNION ALL SELECT 'analyst', 'DATA', 'AUTH_PROJECT_MEMBER' FROM DUAL
) source
ON (target.USERNAME = source.USERNAME
    AND target.ORG_ID = source.ORG_ID
    AND target.AUTHORITY_ID = source.AUTHORITY_ID
    AND target.ASSIGNMENT_TYPE = 'DIRECT'
    AND target.HISTORY_SEQ = 1)
WHEN NOT MATCHED THEN INSERT (
    ASSIGNMENT_ID, USERNAME, ORG_ID, AUTHORITY_ID, ASSIGNMENT_TYPE,
    ASSIGNMENT_STATUS, VALID_FROM, VALID_TO, DELEGATED_BY, HISTORY_SEQ,
    REASON, CREATED_BY
) VALUES (
    SQ_PM_USER_AUTH_HIST.NEXTVAL, source.USERNAME, source.ORG_ID, source.AUTHORITY_ID,
    'DIRECT', 'APPROVED', DATE '2020-01-01', DATE '2099-12-31', NULL, 1,
    '확장 관리 시나리오 초기 권한', 'SYSTEM'
);

