-- 프로젝트 관리 고도화 스키마와 샘플 데이터.
-- 기존 로컬 볼륨에도 한 번 실행할 수 있도록 DDL과 데이터 등록을 재실행 가능하게 구성한다.
BEGIN
    EXECUTE IMMEDIATE q'[
        CREATE TABLE PM_PROJECT (
            PROJECT_ID VARCHAR2(50) NOT NULL,
            PROJECT_NAME VARCHAR2(100) NOT NULL,
            DESCRIPTION VARCHAR2(500),
            PROJECT_STATUS VARCHAR2(20) NOT NULL,
            START_DATE DATE NOT NULL,
            END_DATE DATE NOT NULL,
            OWNER_USERNAME VARCHAR2(100) NOT NULL,
            ACTIVE_YN CHAR(1) DEFAULT 'Y' NOT NULL,
            VERSION_NO NUMBER(19) DEFAULT 1 NOT NULL,
            CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
            CREATED_BY VARCHAR2(100) NOT NULL,
            UPDATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
            UPDATED_BY VARCHAR2(100) NOT NULL,
            CONSTRAINT PK_PM_PROJECT PRIMARY KEY (PROJECT_ID),
            CONSTRAINT FK_PM_PROJECT_OWNER FOREIGN KEY (OWNER_USERNAME)
                REFERENCES PM_USER_PROFILE (USERNAME),
            CONSTRAINT CK_PM_PROJECT_STATUS CHECK (
                PROJECT_STATUS IN ('PLANNED', 'ACTIVE', 'ON_HOLD', 'COMPLETED')),
            CONSTRAINT CK_PM_PROJECT_PERIOD CHECK (END_DATE >= START_DATE),
            CONSTRAINT CK_PM_PROJECT_ACTIVE CHECK (ACTIVE_YN IN ('Y', 'N')),
            CONSTRAINT CK_PM_PROJECT_VERSION CHECK (VERSION_NO >= 1)
        )]';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE q'[
        CREATE TABLE PM_PROJECT_MEMBER (
            PROJECT_ID VARCHAR2(50) NOT NULL,
            USERNAME VARCHAR2(100) NOT NULL,
            PROJECT_ROLE VARCHAR2(20) NOT NULL,
            ACTIVE_YN CHAR(1) DEFAULT 'Y' NOT NULL,
            CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
            CREATED_BY VARCHAR2(100) NOT NULL,
            UPDATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
            UPDATED_BY VARCHAR2(100) NOT NULL,
            CONSTRAINT PK_PM_PROJECT_MEMBER PRIMARY KEY (PROJECT_ID, USERNAME),
            CONSTRAINT FK_PM_PROJECT_MEMBER_PROJECT FOREIGN KEY (PROJECT_ID)
                REFERENCES PM_PROJECT (PROJECT_ID),
            CONSTRAINT FK_PM_PROJECT_MEMBER_USER FOREIGN KEY (USERNAME)
                REFERENCES PM_USER_PROFILE (USERNAME),
            CONSTRAINT CK_PM_PROJECT_MEMBER_ROLE CHECK (
                PROJECT_ROLE IN ('OWNER', 'MANAGER', 'MEMBER', 'VIEWER')),
            CONSTRAINT CK_PM_PROJECT_MEMBER_ACTIVE CHECK (ACTIVE_YN IN ('Y', 'N'))
        )]';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'CREATE INDEX IX_PM_PROJECT_STATUS ON PM_PROJECT (ACTIVE_YN, PROJECT_STATUS, START_DATE)';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'CREATE INDEX IX_PM_PROJECT_MEMBER_USER ON PM_PROJECT_MEMBER (USERNAME, ACTIVE_YN, PROJECT_ID)';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

COMMENT ON TABLE PM_PROJECT IS '프로젝트 마스터와 일정 및 책임자 정보';
COMMENT ON TABLE PM_PROJECT_MEMBER IS '프로젝트별 참여 사용자와 역할';

MERGE INTO PM_MENU target
USING (
    SELECT 'SYSTEM_PROJECT' MENU_ID, 'SYSTEM' PARENT_MENU_ID, '프로젝트 관리' MENU_NAME,
           '#project' MENU_PATH, 35 SORT_ORDER FROM DUAL
) source
ON (target.MENU_ID = source.MENU_ID)
WHEN NOT MATCHED THEN INSERT (
    MENU_ID, PARENT_MENU_ID, MENU_NAME, MENU_PATH, SORT_ORDER,
    ACTIVE_YN, DISPLAY_YN, PUBLIC_YN, CREATED_BY, UPDATED_BY
) VALUES (
    source.MENU_ID, source.PARENT_MENU_ID, source.MENU_NAME, source.MENU_PATH,
    source.SORT_ORDER, 'Y', 'Y', 'N', 'SYSTEM', 'SYSTEM'
);

MERGE INTO PM_PROGRAM target
USING (SELECT 'PROJECT' PROGRAM_ID, '프로젝트 관리' PROGRAM_NAME,
              '프로젝트와 참여자 관리 업무' DESCRIPTION FROM DUAL) source
ON (target.PROGRAM_ID = source.PROGRAM_ID)
WHEN NOT MATCHED THEN INSERT (
    PROGRAM_ID, PROGRAM_NAME, DESCRIPTION, ACTIVE_YN, CREATED_BY, UPDATED_BY
) VALUES (
    source.PROGRAM_ID, source.PROGRAM_NAME, source.DESCRIPTION, 'Y', 'SYSTEM', 'SYSTEM'
);

MERGE INTO PM_PROGRAM_ACTION target
USING (
    SELECT 'SYSTEM_PROJECT' MENU_ID, 'PROJECT' PROGRAM_ID, 'PROJECT_READ' ACTION_ID,
           '프로젝트 조회' ACTION_NAME, 'btnProjectRead' COMPONENT_ID, 10 SORT_ORDER FROM DUAL
    UNION ALL
    SELECT 'SYSTEM_PROJECT', 'PROJECT', 'PROJECT_UPDATE',
           '프로젝트 변경', 'btnProjectSave', 20 FROM DUAL
) source
ON (target.MENU_ID = source.MENU_ID
    AND target.PROGRAM_ID = source.PROGRAM_ID
    AND target.ACTION_ID = source.ACTION_ID)
WHEN NOT MATCHED THEN INSERT (
    MENU_ID, PROGRAM_ID, ACTION_ID, ACTION_NAME, COMPONENT_ID,
    SORT_ORDER, ACTIVE_YN, CREATED_BY, UPDATED_BY
) VALUES (
    source.MENU_ID, source.PROGRAM_ID, source.ACTION_ID, source.ACTION_NAME,
    source.COMPONENT_ID, source.SORT_ORDER, 'Y', 'SYSTEM', 'SYSTEM'
);

MERGE INTO PM_AUTH_MENU target
USING (SELECT 'AUTH_SYSTEM_ADMIN' AUTHORITY_ID, 'SYSTEM_PROJECT' MENU_ID FROM DUAL) source
ON (target.AUTHORITY_ID = source.AUTHORITY_ID AND target.MENU_ID = source.MENU_ID)
WHEN NOT MATCHED THEN INSERT (AUTHORITY_ID, MENU_ID, CREATED_BY)
VALUES (source.AUTHORITY_ID, source.MENU_ID, 'SYSTEM');

MERGE INTO PM_AUTH_ACTION target
USING (
    SELECT 'AUTH_SYSTEM_ADMIN' AUTHORITY_ID, 'SYSTEM_PROJECT' MENU_ID,
           'PROJECT' PROGRAM_ID, 'PROJECT_READ' ACTION_ID FROM DUAL
    UNION ALL
    SELECT 'AUTH_SYSTEM_ADMIN', 'SYSTEM_PROJECT', 'PROJECT', 'PROJECT_UPDATE' FROM DUAL
) source
ON (target.AUTHORITY_ID = source.AUTHORITY_ID
    AND target.MENU_ID = source.MENU_ID
    AND target.PROGRAM_ID = source.PROGRAM_ID
    AND target.ACTION_ID = source.ACTION_ID)
WHEN NOT MATCHED THEN INSERT (
    AUTHORITY_ID, MENU_ID, PROGRAM_ID, ACTION_ID, CREATED_BY
) VALUES (
    source.AUTHORITY_ID, source.MENU_ID, source.PROGRAM_ID, source.ACTION_ID, 'SYSTEM'
);

MERGE INTO PM_PROJECT target
USING (
    SELECT 'PRJ_ACCESS_RENEWAL' PROJECT_ID, '통합 권한 체계 고도화' PROJECT_NAME,
           '권한·메뉴·감사 체계를 운영 수준으로 개선' DESCRIPTION, 'ACTIVE' PROJECT_STATUS,
           DATE '2026-08-01' START_DATE, DATE '2026-11-30' END_DATE, 'admin' OWNER_USERNAME FROM DUAL
    UNION ALL
    SELECT 'PRJ_DATA_HUB', '데이터 허브 구축', '업무 기준정보와 공통코드 통합', 'PLANNED',
           DATE '2026-10-01', DATE '2027-03-31', 'manager' FROM DUAL
    UNION ALL
    SELECT 'PRJ_MOBILE_PORTAL', '모바일 업무 포털', '핵심 업무의 모바일 접근성 개선', 'ON_HOLD',
           DATE '2026-06-01', DATE '2026-12-31', 'admin' FROM DUAL
) source
ON (target.PROJECT_ID = source.PROJECT_ID)
WHEN NOT MATCHED THEN INSERT (
    PROJECT_ID, PROJECT_NAME, DESCRIPTION, PROJECT_STATUS, START_DATE, END_DATE,
    OWNER_USERNAME, ACTIVE_YN, VERSION_NO, CREATED_BY, UPDATED_BY
) VALUES (
    source.PROJECT_ID, source.PROJECT_NAME, source.DESCRIPTION, source.PROJECT_STATUS,
    source.START_DATE, source.END_DATE, source.OWNER_USERNAME, 'Y', 1, 'SYSTEM', 'SYSTEM'
);

MERGE INTO PM_PROJECT_MEMBER target
USING (
    SELECT 'PRJ_ACCESS_RENEWAL' PROJECT_ID, 'admin' USERNAME, 'OWNER' PROJECT_ROLE FROM DUAL
    UNION ALL SELECT 'PRJ_ACCESS_RENEWAL', 'manager', 'MANAGER' FROM DUAL
    UNION ALL SELECT 'PRJ_ACCESS_RENEWAL', 'viewer', 'VIEWER' FROM DUAL
    UNION ALL SELECT 'PRJ_DATA_HUB', 'manager', 'OWNER' FROM DUAL
    UNION ALL SELECT 'PRJ_DATA_HUB', 'viewer', 'MEMBER' FROM DUAL
    UNION ALL SELECT 'PRJ_MOBILE_PORTAL', 'admin', 'OWNER' FROM DUAL
    UNION ALL SELECT 'PRJ_MOBILE_PORTAL', 'delegate', 'MEMBER' FROM DUAL
) source
ON (target.PROJECT_ID = source.PROJECT_ID AND target.USERNAME = source.USERNAME)
WHEN NOT MATCHED THEN INSERT (
    PROJECT_ID, USERNAME, PROJECT_ROLE, ACTIVE_YN, CREATED_BY, UPDATED_BY
) VALUES (
    source.PROJECT_ID, source.USERNAME, source.PROJECT_ROLE, 'Y', 'SYSTEM', 'SYSTEM'
);

MERGE INTO PM_DOMAIN_VERSION target
USING (SELECT 'PROJECT' DOMAIN_CODE, 1 VERSION_NO FROM DUAL) source
ON (target.DOMAIN_CODE = source.DOMAIN_CODE)
WHEN NOT MATCHED THEN INSERT (DOMAIN_CODE, VERSION_NO, UPDATED_BY)
VALUES (source.DOMAIN_CODE, source.VERSION_NO, 'SYSTEM');

COMMIT;
