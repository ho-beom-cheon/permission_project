-- 프로젝트 상태 변경 이력. 기존 로컬 볼륨에도 안전하게 재실행할 수 있다.
BEGIN
    EXECUTE IMMEDIATE q'[
        CREATE TABLE PM_PROJECT_STATUS_HISTORY (
            PROJECT_ID VARCHAR2(50) NOT NULL,
            SEQUENCE_NO NUMBER(19) NOT NULL,
            FROM_STATUS VARCHAR2(20),
            TO_STATUS VARCHAR2(20) NOT NULL,
            CHANGED_BY VARCHAR2(100) NOT NULL,
            CHANGE_REASON VARCHAR2(300) NOT NULL,
            CHANGED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
            CONSTRAINT PK_PM_PROJECT_STATUS_HISTORY
                PRIMARY KEY (PROJECT_ID, SEQUENCE_NO),
            CONSTRAINT FK_PM_PROJECT_HISTORY_PROJECT
                FOREIGN KEY (PROJECT_ID) REFERENCES PM_PROJECT (PROJECT_ID),
            CONSTRAINT CK_PM_PROJECT_HISTORY_SEQUENCE CHECK (SEQUENCE_NO >= 1),
            CONSTRAINT CK_PM_PROJECT_HISTORY_FROM CHECK (
                FROM_STATUS IS NULL OR
                FROM_STATUS IN ('PLANNED', 'ACTIVE', 'ON_HOLD', 'COMPLETED')
            ),
            CONSTRAINT CK_PM_PROJECT_HISTORY_TO CHECK (
                TO_STATUS IN ('PLANNED', 'ACTIVE', 'ON_HOLD', 'COMPLETED')
            )
        )]';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE q'[
        CREATE INDEX IX_PM_PROJECT_HISTORY_TIME
            ON PM_PROJECT_STATUS_HISTORY (PROJECT_ID, CHANGED_AT)
    ]';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

COMMENT ON TABLE PM_PROJECT_STATUS_HISTORY IS '프로젝트 상태 전이 사유와 행위자 이력';
COMMENT ON COLUMN PM_PROJECT_STATUS_HISTORY.SEQUENCE_NO IS '프로젝트별 상태 이력 순번';
COMMENT ON COLUMN PM_PROJECT_STATUS_HISTORY.FROM_STATUS IS '변경 전 상태. 최초 등록은 NULL';
COMMENT ON COLUMN PM_PROJECT_STATUS_HISTORY.TO_STATUS IS '변경 후 상태';
COMMENT ON COLUMN PM_PROJECT_STATUS_HISTORY.CHANGED_BY IS '상태 변경 행위자 또는 SYSTEM';
COMMENT ON COLUMN PM_PROJECT_STATUS_HISTORY.CHANGE_REASON IS '상태 변경 사유';

-- 기존 프로젝트에는 현재 상태를 최초 기준 이력으로 한 번만 등록한다.
MERGE INTO PM_PROJECT_STATUS_HISTORY target
USING (
    SELECT PROJECT_ID,
           PROJECT_STATUS TO_STATUS,
           OWNER_USERNAME CHANGED_BY
    FROM PM_PROJECT
) source
ON (target.PROJECT_ID = source.PROJECT_ID AND target.SEQUENCE_NO = 1)
WHEN NOT MATCHED THEN INSERT (
    PROJECT_ID,
    SEQUENCE_NO,
    FROM_STATUS,
    TO_STATUS,
    CHANGED_BY,
    CHANGE_REASON,
    CHANGED_AT
) VALUES (
    source.PROJECT_ID,
    1,
    NULL,
    source.TO_STATUS,
    source.CHANGED_BY,
    '프로젝트 상태 이력 기능 적용 시점의 기준 상태',
    SYSTIMESTAMP
);

COMMIT;
