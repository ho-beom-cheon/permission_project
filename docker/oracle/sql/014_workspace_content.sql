WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET DEFINE OFF
-- 새 업무 데이터는 비어 있는 상태로 시작한다. 화면 예제 데이터를 운영 콘텐츠로 옮기지 않는다.
DECLARE
    object_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO object_count FROM USER_TABLES WHERE TABLE_NAME = 'PM_CONTENT';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE PM_CONTENT (
            CONTENT_ID NUMBER(19) PRIMARY KEY,
            CONTENT_TYPE VARCHAR2(20 CHAR) NOT NULL,
            TITLE VARCHAR2(100 CHAR) NOT NULL,
            BODY CLOB NOT NULL,
            STATUS_CODE VARCHAR2(50 CHAR) NOT NULL,
            AUTHOR VARCHAR2(100 CHAR) NOT NULL,
            CREATED_AT TIMESTAMP(6) NOT NULL,
            UPDATED_AT TIMESTAMP(6) NOT NULL,
            VERSION_NO NUMBER(19) DEFAULT 1 NOT NULL CHECK (VERSION_NO > 0))';
    END IF;
    SELECT COUNT(*) INTO object_count FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'PM_CONTENT_SEQ';
    IF object_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE SEQUENCE PM_CONTENT_SEQ START WITH 1 INCREMENT BY 1 NOCYCLE';
    END IF;
END;
/
COMMENT ON TABLE PM_CONTENT IS '사용자 업무 콘텐츠';
COMMENT ON COLUMN PM_CONTENT.CONTENT_ID IS '콘텐츠 식별자';
COMMENT ON COLUMN PM_CONTENT.CONTENT_TYPE IS '업무, 공지, 자료, 소식';
COMMENT ON COLUMN PM_CONTENT.TITLE IS '콘텐츠 제목';
COMMENT ON COLUMN PM_CONTENT.BODY IS '일반 텍스트 본문';
COMMENT ON COLUMN PM_CONTENT.STATUS_CODE IS 'ARTICLE_STATUS 코드';
COMMENT ON COLUMN PM_CONTENT.AUTHOR IS '최초 작성자 계정';
COMMENT ON COLUMN PM_CONTENT.CREATED_AT IS '최초 등록 시각 UTC';
COMMENT ON COLUMN PM_CONTENT.UPDATED_AT IS '최종 변경 시각 UTC';
COMMENT ON COLUMN PM_CONTENT.VERSION_NO IS '동시 변경 검사용 버전';
