-- 권한 신청·승인·반려·취소 워크플로.
-- 신규 볼륨과 기존 로컬 볼륨 모두에서 한 번씩 안전하게 적용할 수 있도록 객체 생성을 멱등 처리한다.
BEGIN
    EXECUTE IMMEDIATE 'CREATE SEQUENCE SQ_PM_AUTH_REQUEST START WITH 1 INCREMENT BY 1 CACHE 100 NOCYCLE';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE q'[
        CREATE TABLE PM_AUTH_REQUEST (
            REQUEST_ID NUMBER(19) NOT NULL,
            REQUESTER_USERNAME VARCHAR2(100) NOT NULL,
            TARGET_USERNAME VARCHAR2(100) NOT NULL,
            ORG_ID VARCHAR2(30) NOT NULL,
            AUTHORITY_ID VARCHAR2(50) NOT NULL,
            ASSIGNMENT_TYPE VARCHAR2(10) NOT NULL,
            REQUEST_STATUS VARCHAR2(12) NOT NULL,
            VALID_FROM DATE NOT NULL,
            VALID_TO DATE NOT NULL,
            DELEGATED_BY VARCHAR2(100),
            REQUEST_REASON VARCHAR2(500) NOT NULL,
            DECISION_REASON VARCHAR2(500),
            VERSION_NO NUMBER(19) DEFAULT 1 NOT NULL,
            REQUESTED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
            DECIDED_AT TIMESTAMP(6),
            DECIDED_BY VARCHAR2(100),
            CONSTRAINT PK_PM_AUTH_REQUEST PRIMARY KEY (REQUEST_ID),
            CONSTRAINT FK_PM_AR_REQUESTER FOREIGN KEY (REQUESTER_USERNAME)
                REFERENCES PM_USER_PROFILE (USERNAME),
            CONSTRAINT FK_PM_AR_TARGET FOREIGN KEY (TARGET_USERNAME)
                REFERENCES PM_USER_PROFILE (USERNAME),
            CONSTRAINT FK_PM_AR_ORG FOREIGN KEY (ORG_ID)
                REFERENCES PM_ORGANIZATION (ORG_ID),
            CONSTRAINT FK_PM_AR_AUTH FOREIGN KEY (AUTHORITY_ID)
                REFERENCES PM_AUTHORITY (AUTHORITY_ID),
            CONSTRAINT FK_PM_AR_DELEGATOR FOREIGN KEY (DELEGATED_BY)
                REFERENCES PM_USER_PROFILE (USERNAME),
            CONSTRAINT FK_PM_AR_DECIDER FOREIGN KEY (DECIDED_BY)
                REFERENCES PM_USER_PROFILE (USERNAME),
            CONSTRAINT CK_PM_AR_TYPE CHECK (ASSIGNMENT_TYPE IN ('DIRECT', 'DELEGATED')),
            CONSTRAINT CK_PM_AR_STATUS CHECK (
                REQUEST_STATUS IN ('REQUESTED', 'APPROVED', 'REJECTED', 'CANCELLED')),
            CONSTRAINT CK_PM_AR_PERIOD CHECK (VALID_TO >= VALID_FROM),
            CONSTRAINT CK_PM_AR_SOURCE CHECK (
                (ASSIGNMENT_TYPE = 'DIRECT' AND DELEGATED_BY IS NULL)
                OR (ASSIGNMENT_TYPE = 'DELEGATED' AND DELEGATED_BY IS NOT NULL)
            ),
            CONSTRAINT CK_PM_AR_VERSION CHECK (VERSION_NO >= 1),
            CONSTRAINT CK_PM_AR_DECISION CHECK (
                (REQUEST_STATUS = 'REQUESTED' AND DECIDED_AT IS NULL AND DECIDED_BY IS NULL)
                OR (REQUEST_STATUS IN ('APPROVED', 'REJECTED')
                    AND DECIDED_AT IS NOT NULL AND DECIDED_BY IS NOT NULL)
                OR REQUEST_STATUS = 'CANCELLED'
            )
        )]';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'CREATE INDEX IX_PM_AR_QUEUE ON PM_AUTH_REQUEST (REQUEST_STATUS, REQUESTED_AT, REQUEST_ID)';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'CREATE INDEX IX_PM_AR_TARGET ON PM_AUTH_REQUEST (TARGET_USERNAME, ORG_ID, REQUESTED_AT DESC)';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

COMMENT ON TABLE PM_AUTH_REQUEST IS '업무 권한 신청과 승인·반려·취소 상태 이력';

MERGE INTO PM_DOMAIN_VERSION target
USING (SELECT 'AUTH_REQUEST' DOMAIN_CODE, 1 VERSION_NO FROM DUAL) source
ON (target.DOMAIN_CODE = source.DOMAIN_CODE)
WHEN NOT MATCHED THEN INSERT (DOMAIN_CODE, VERSION_NO, UPDATED_BY)
VALUES (source.DOMAIN_CODE, source.VERSION_NO, 'SYSTEM');

COMMIT;
