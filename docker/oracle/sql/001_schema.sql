CREATE SEQUENCE SQ_PM_USER_AUTH_HIST START WITH 1 INCREMENT BY 1 CACHE 100 NOCYCLE;

CREATE TABLE PM_USER_AUTH_HIST (
    ASSIGNMENT_ID NUMBER(19) NOT NULL,
    USERNAME VARCHAR2(100) NOT NULL,
    ORG_ID VARCHAR2(30) NOT NULL,
    AUTHORITY_ID VARCHAR2(50) NOT NULL,
    ASSIGNMENT_TYPE VARCHAR2(10) NOT NULL,
    ASSIGNMENT_STATUS VARCHAR2(10) NOT NULL,
    VALID_FROM DATE NOT NULL,
    VALID_TO DATE NOT NULL,
    DELEGATED_BY VARCHAR2(100),
    HISTORY_SEQ NUMBER(10) NOT NULL,
    REASON VARCHAR2(500),
    CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY VARCHAR2(100) NOT NULL,
    CONSTRAINT PK_PM_USER_AUTH_HIST PRIMARY KEY (ASSIGNMENT_ID),
    CONSTRAINT UK_PM_USER_AUTH_HIST UNIQUE
        (USERNAME, ORG_ID, AUTHORITY_ID, ASSIGNMENT_TYPE, HISTORY_SEQ),
    CONSTRAINT FK_PM_UAH_USER FOREIGN KEY (USERNAME) REFERENCES PM_USER_PROFILE (USERNAME),
    CONSTRAINT FK_PM_UAH_ORG FOREIGN KEY (ORG_ID) REFERENCES PM_ORGANIZATION (ORG_ID),
    CONSTRAINT FK_PM_UAH_AUTH FOREIGN KEY (AUTHORITY_ID) REFERENCES PM_AUTHORITY (AUTHORITY_ID),
    CONSTRAINT FK_PM_UAH_DELEGATOR FOREIGN KEY (DELEGATED_BY) REFERENCES PM_USER_PROFILE (USERNAME),
    CONSTRAINT CK_PM_UAH_TYPE CHECK (ASSIGNMENT_TYPE IN ('DIRECT', 'DELEGATED')),
    CONSTRAINT CK_PM_UAH_STATUS CHECK (ASSIGNMENT_STATUS IN ('PENDING', 'APPROVED', 'REVOKED')),
    CONSTRAINT CK_PM_UAH_PERIOD CHECK (VALID_TO >= VALID_FROM),
    CONSTRAINT CK_PM_UAH_SOURCE CHECK (
        (ASSIGNMENT_TYPE = 'DIRECT' AND DELEGATED_BY IS NULL)
        OR (ASSIGNMENT_TYPE = 'DELEGATED' AND DELEGATED_BY IS NOT NULL)
    )
);

