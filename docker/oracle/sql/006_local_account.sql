-- SSO를 사용하지 않는 단일 서버용 로컬 로그인 계정.
-- 암호는 Spring Security가 인식하는 단방향 해시만 저장하며 평문 컬럼은 두지 않는다.
BEGIN
    EXECUTE IMMEDIATE q'[
        CREATE TABLE PM_LOCAL_ACCOUNT (
            USERNAME VARCHAR2(100) NOT NULL,
            PASSWORD_HASH VARCHAR2(200) NOT NULL,
            ENABLED_YN CHAR(1) DEFAULT 'Y' NOT NULL,
            PASSWORD_CHANGED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
            CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
            CREATED_BY VARCHAR2(100) NOT NULL,
            UPDATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
            UPDATED_BY VARCHAR2(100) NOT NULL,
            CONSTRAINT PK_PM_LOCAL_ACCOUNT PRIMARY KEY (USERNAME),
            CONSTRAINT FK_PM_LOCAL_ACCOUNT_USER FOREIGN KEY (USERNAME)
                REFERENCES PM_USER_PROFILE (USERNAME),
            CONSTRAINT CK_PM_LOCAL_ACCOUNT_ENABLED CHECK (ENABLED_YN IN ('Y', 'N'))
        )]';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

COMMENT ON TABLE PM_LOCAL_ACCOUNT IS '단일 서버 폼 로그인용 암호 해시 계정';

MERGE INTO PM_DOMAIN_VERSION target
USING (SELECT 'LOCAL_ACCOUNT' DOMAIN_CODE, 1 VERSION_NO FROM DUAL) source
ON (target.DOMAIN_CODE = source.DOMAIN_CODE)
WHEN NOT MATCHED THEN INSERT (DOMAIN_CODE, VERSION_NO, UPDATED_BY)
VALUES (source.DOMAIN_CODE, source.VERSION_NO, 'SYSTEM');

COMMIT;
