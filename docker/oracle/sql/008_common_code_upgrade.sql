-- 공통코드 그룹 관리 화면의 정렬 순서와 시스템 보호 여부를 영속화한다.
BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE PM_CODE_GROUP ADD (SORT_ORDER NUMBER(5) DEFAULT 999 NOT NULL)';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -1430 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE PM_CODE_GROUP ADD (SYSTEM_YN CHAR(1) DEFAULT ''N'' NOT NULL)';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -1430 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE q'[
        ALTER TABLE PM_CODE_GROUP ADD CONSTRAINT CK_PM_CODE_GROUP_SYSTEM
        CHECK (SYSTEM_YN IN ('Y', 'N'))]';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -2264 THEN RAISE; END IF;
END;
/

UPDATE PM_CODE_GROUP
SET SYSTEM_YN = 'Y', UPDATED_AT = SYSTIMESTAMP, UPDATED_BY = 'SYSTEM'
WHERE CREATED_BY = 'SYSTEM';

MERGE INTO PM_CODE_GROUP target
USING (
    SELECT 'USE_YN' GROUP_CODE, 10 SORT_ORDER FROM DUAL
    UNION ALL SELECT 'ARTICLE_STATUS', 20 FROM DUAL
    UNION ALL SELECT 'AUTH_STATUS', 30 FROM DUAL
    UNION ALL SELECT 'AUTH_TYPE', 40 FROM DUAL
    UNION ALL SELECT 'ASSIGNMENT_TYPE', 40 FROM DUAL
    UNION ALL SELECT 'REQUEST_STATUS', 45 FROM DUAL
    UNION ALL SELECT 'PROJECT_STATUS', 50 FROM DUAL
    UNION ALL SELECT 'PROJECT_PRIORITY', 55 FROM DUAL
    UNION ALL SELECT 'PROJECT_ROLE', 60 FROM DUAL
    UNION ALL SELECT 'PROGRAM_TYPE', 70 FROM DUAL
    UNION ALL SELECT 'REGION', 80 FROM DUAL
    UNION ALL SELECT 'AUDIT_RESULT', 90 FROM DUAL
    UNION ALL SELECT 'ORGANIZATION_TYPE', 100 FROM DUAL
) source
ON (target.GROUP_CODE = source.GROUP_CODE)
WHEN MATCHED THEN UPDATE SET target.SORT_ORDER = source.SORT_ORDER;

MERGE INTO PM_DOMAIN_VERSION target
USING (SELECT 'COMMON_CODE' DOMAIN_CODE, 2 VERSION_NO FROM DUAL) source
ON (target.DOMAIN_CODE = source.DOMAIN_CODE)
WHEN MATCHED THEN UPDATE SET
    target.VERSION_NO = GREATEST(target.VERSION_NO, source.VERSION_NO),
    target.UPDATED_AT = SYSTIMESTAMP,
    target.UPDATED_BY = 'SYSTEM'
WHEN NOT MATCHED THEN INSERT (DOMAIN_CODE, VERSION_NO, UPDATED_BY)
VALUES (source.DOMAIN_CODE, source.VERSION_NO, 'SYSTEM');

COMMIT;
